// Пример 4: Чтение всего файла целиком за один раз в память (fs::read_to_string)
// -------------------------------------------------------------------------------
// Читает весь файл за один-единственный системный вызов сразу в String или Vec<u8>.
//
// Аналогия из подкаста:
// «Притащить домой здоровенную бутыль с водой. Быстро, но таскать неудобно».
//
// Плюсы:  Абсолютный рекорд по скорости для небольших файлов.
// Минусы: Требует ровно столько оперативной памяти, сколько весит файл.
//         На файле в несколько гигабайт программа завершится с ошибкой OOM (Out Of Memory).

use rust_bufreader_examples::{ensure_test_file, DEFAULT_FILE_PATH, DEFAULT_LINES};
use std::fs;
use std::io;
use std::time::Instant;

fn main() -> io::Result<()> {
    ensure_test_file(DEFAULT_FILE_PATH, DEFAULT_LINES)?;

    println!("============================================================");
    println!("Пример 4: Чтение всего файла целиком за раз (fs::read_to_string)");
    println!("Рекордная скорость, но файл должен полностью помещаться в RAM");
    println!("============================================================");

    let start = Instant::now();

    // Читаем весь файл сразу в память
    let contents = fs::read_to_string(DEFAULT_FILE_PATH)?;

    let mut lines_count = 0usize;
    for _ in contents.lines() {
        lines_count += 1;
    }

    let duration = start.elapsed();
    println!("Прочитано строк:   {}", lines_count);
    println!("Размер в памяти:   {:.2} МБ", contents.len() as f64 / (1024.0 * 1024.0));
    println!("Время выполнения:  {:.2?} (абсолютный рекорд)", duration);
    println!("Предостережение:   Используйте только для файлов заведомо небольшого размера!\n");

    Ok(())
}
